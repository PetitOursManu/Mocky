#!/usr/bin/env node
/**
 * Writes src/ui/mockyLoaderWord.ts — the word "Mocky", written by hand, for the
 * generation loader (`MockyLoader`).
 *
 * WHY GENERATED, AND WHY HERE
 *
 * The loader is drawn by Tegaki (MIT, https://tegaki.ink): a real handwriting
 * font traced stroke by stroke, in the order a pen would take — what the first
 * hand-drawn path ("Mookn") and then the wipe across a system script could not
 * be. Tegaki can do that at runtime, but the word never changes, so it is done
 * once, here: its CLI shapes the text with harfbuzz and clips the ink to the
 * letter outlines, and what comes out is a self-drawing SVG — paths and CSS
 * keyframes, no script, no font file, nothing for the app to load. The app ships
 * the result and not the library.
 *
 * Two versions: the loop the loader plays, and the finished word for reduced
 * motion — under `prefers-reduced-motion` the app's own rule collapses every
 * animation onto its last keyframe, and the last keyframe of a loop is the word
 * faded out.
 *
 * Parisienne (Astigmatic, SIL OFL 1.1), from the bundles Tegaki ships: joined,
 * legible at 32 px, and closest to the script the loader asked the system for.
 *
 * Usage:  npm run build:loader-word   (tegaki is a devDependency, pinned exactly)
 */
import { execFileSync } from 'node:child_process'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const cli = path.join(root, 'node_modules', 'tegaki', 'dist', 'cli.mjs')
const version = JSON.parse(fs.readFileSync(path.join(root, 'node_modules', 'tegaki', 'package.json'), 'utf8')).version

/** The settings the word is written with — changing one is a re-run of this script. */
const FONT = 'parisienne'
/** ~3.3 s a loop: the old wipe's 3.2 s, so the rhythm people know does not change. */
const SPEED = 5
const LOOP_HOLD = 0.5

function svg(mode) {
  const args = [cli, 'Mocky', '--font', FONT, '--mode', mode, '--color', 'currentColor', '-o', '-']
  if (mode === 'loop') args.push('--speed', String(SPEED), '--loop-hold', String(LOOP_HOLD))
  const out = execFileSync(process.execPath, args, { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] })
  // The size is the loader's to set: drop the fixed width and height and keep
  // the viewBox, so the word scales with the box it is put in.
  return out.trim().replace(/<svg ([^>]*?)\swidth="[^"]*"\s+height="[^"]*"/, '<svg $1')
}

const loop = svg('loop')
const still = svg('static')
const banner = `// GENERATED by scripts/build-loader-word.mjs from tegaki ${version} — do not edit.
// The word "Mocky" in Parisienne (SIL OFL 1.1), traced by Tegaki (MIT,
// Copyright (c) Gokhan Kurt, https://github.com/gkurt/tegaki).
`
const file = `${banner}
/** The loader's loop: written, held, faded, written again. Class and id names start with \`tk-\`. */
export const MOCKY_WORD_LOOP = ${JSON.stringify(loop)}

/** The finished word, for reduced motion. */
export const MOCKY_WORD_STILL = ${JSON.stringify(still)}
`
fs.writeFileSync(path.join(root, 'src', 'ui', 'mockyLoaderWord.ts'), file)
console.log(`mockyLoaderWord.ts: loop ${(loop.length / 1024).toFixed(1)} KB, still ${(still.length / 1024).toFixed(1)} KB`)
