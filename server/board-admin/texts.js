/** `fr` unless the Board asked for English: Mocky's own default language. */
export function langOf(req) {
  const first = String(req?.headers?.['accept-language'] || '')
    .split(',')[0]
    .trim()
    .toLowerCase()
  return first.startsWith('en') ? 'en' : 'fr'
}

/** `t(key, vars)` in `lang`; a missing key shows itself rather than nothing. */
export function translator(lang) {
  const dict = TEXTS[lang] || TEXTS.fr
  return (key, vars) => {
    const s = dict[key] ?? TEXTS.fr[key] ?? key
    return vars ? s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined && vars[k] !== null ? String(vars[k]) : m)) : s
  }
}
