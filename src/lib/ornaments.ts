import { FRAME_SHAPES } from './frameShapes'

/**
 * The decorative shapes a page may draw — `<Ornament shape="…">`.
 *
 * Every document brief asked for "blobs, circles, arcs, waves, stripes, dotted
 * grids, a starburst badge", and the only way the model had to draw one was a
 * CSS box or a hand-written `<svg><path d=…>`, which the generation prompt
 * forbids past a few commands because a path cut off mid-string breaks the
 * render. So a flyer got the shapes a `rounded-full` can make, and nothing that
 * was drawn by a hand. This is the same answer `<ShapeFrame>` gave to pictures:
 * a closed list of names, drawn once, here, and tested.
 *
 * Three kinds, because they are stretched three ways:
 *  - `fill`    — a solid shape. Every frame's hole that is not a photo frame
 *                (`frameShapes.ts`, the one source of those paths), plus a ring.
 *                Stretched to its box like a frame, keeping `ratio` unless the
 *                page sizes it.
 *  - `line`    — a stroke a hand would draw: a squiggle under a word, a circle
 *                scribbled round it, a curved arrow. Stretched too, but its
 *                stroke is `non-scaling`, so a squiggle twice as wide is not a
 *                squiggle twice as thick.
 *  - `pattern` — a texture: dots, a grid, stripes. NOT stretched — a dot grid
 *                stretched is a grid of ellipses — but sliced: the 100-unit
 *                square covers the box and the excess is cut. Its geometry is
 *                generated by the snippet at render time from a name and a
 *                density, so none of it is stored in the preview's source.
 */

export type OrnamentKind = 'fill' | 'line' | 'pattern'

export interface Ornament {
  id: string
  kind: OrnamentKind
  /** Width over height it was drawn for. Patterns have none: they take their box. */
  ratio: number
  /** Paths in a 0–100 box (fill: `evenodd`; line: stroked, round caps). Empty for a pattern. */
  d: string
}

const r2 = (n: number) => Math.round(n * 100) / 100
const fmt = (n: number) => String(r2(n) === 0 ? 0 : r2(n))

/** A wave along `y` from x=`from` to x=`to`, as quadratics — `frameShapes.ts`'s waveEdge, open. */
function waveLine(from: number, to: number, y: number, amp: number, halves: number): string {
  const step = (to - from) / halves
  let d = `M${fmt(from)} ${fmt(y)}`
  for (let i = 0; i < halves; i++) {
    const x = from + step * i
    const sign = i % 2 === 0 ? -1 : 1
    d += `Q${fmt(x + step / 2)} ${fmt(y + sign * amp * 2)} ${fmt(x + step)} ${fmt(y)}`
  }
  return d
}

function zigzagLine(from: number, to: number, lo: number, hi: number, teeth: number): string {
  const step = (to - from) / (teeth * 2)
  let d = `M${fmt(from)} ${fmt(hi)}`
  for (let i = 1; i <= teeth * 2; i++) d += `L${fmt(from + step * i)} ${fmt(i % 2 ? lo : hi)}`
  return d
}

/**
 * A spiral of half circles around two centres four units apart, the classic
 * compass construction: each half turn is a plain arc, so no point is stored
 * that a renderer could round differently.
 */
function spiral(turns: number): string {
  let d = 'M50 50'
  for (let i = 1; i <= turns * 2; i++) {
    const r = i * 4
    // Odd half turns are centred on 54 and end on its right, even ones on 50
    // and end on its left: each starts where the last one ended.
    d += `A${r} ${r} 0 0 1 ${fmt(i % 2 ? 54 + r : 50 - r)} 50`
  }
  return d
}

/** Short strokes on a ring, like the rays of a sun drawn with a pen. */
function rays(n: number, inner: number, outer: number): string {
  let d = ''
  for (let i = 0; i < n; i++) {
    const a = -Math.PI / 2 + (i * 2 * Math.PI) / n
    d += `M${fmt(50 + Math.cos(a) * inner)} ${fmt(50 + Math.sin(a) * inner)}L${fmt(50 + Math.cos(a) * outer)} ${fmt(50 + Math.sin(a) * outer)}`
  }
  return d
}

const circlePath = (cx: number, cy: number, r: number) =>
  `M${fmt(cx)} ${fmt(cy - r)}A${fmt(r)} ${fmt(r)} 0 1 1 ${fmt(cx)} ${fmt(cy + r)}A${fmt(r)} ${fmt(r)} 0 1 1 ${fmt(cx)} ${fmt(cy - r)}Z`

