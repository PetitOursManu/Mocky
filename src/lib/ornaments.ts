import { FRAME_SHAPES } from './frameShapes'

/**
 * The decorative shapes a page may draw — `<Ornament shape="…">`.
 *
 * Every document brief asked for "blobs, circles, arcs, waves, stripes, dotted
 * grids, a starburst badge", and the only way the model had to draw one was a
 * CSS box or a hand-written `<svg><path d=…>`, which the generation prompt
 * forbids past a few commands because a path cut off mid-string breaks the
 * render. So a flyer got the shapes a `rounded-full` can make, and nothing that
 * was drawn by a hand. This is the same answer `<ShapeFrame>` gave to pictures:
 * a closed list of names, drawn once, here, and tested.
 *
 * Five kinds. The first three are stretched three ways:
 *  - `fill`    — a solid shape. Every frame's hole that is not a photo frame
 *                (`frameShapes.ts`, the one source of those paths), plus a ring.
 *                Stretched to its box like a frame, keeping `ratio` unless the
 *                page sizes it.
 *  - `line`    — a stroke a hand would draw: a squiggle under a word, a circle
 *                scribbled round it, a curved arrow. Stretched too, but its
 *                stroke is `non-scaling`, so a squiggle twice as wide is not a
 *                squiggle twice as thick.
 *  - `pattern` — a texture: dots, a grid, stripes. NOT stretched — a dot grid
 *                stretched is a grid of ellipses — but sliced: the 100-unit
 *                square covers the box and the excess is cut. Its geometry is
 *                generated by the snippet at render time from a name and a
 *                density, so none of it is stored in the preview's source.
 * The last two are fills that say more than one thing:
 *  - `fluid`   — an organic fill with a second path in the page's `accent`: the
 *                ribbon across a blob, the ring round a pebble (`layers`).
 *  - `motion`  — a sign that moves, a loader or a beat (`motion`, `moves`), and
 *                holds still wherever an entrance would.
 */

export type OrnamentKind = 'fill' | 'fluid' | 'line' | 'pattern' | 'motion'

/**
 * A second (third…) path over the main one. A fluid ribbon is a blob AND the
 * stroke that runs across it, in another colour; a loader is dots that turn
 * round a ring that does not. One `d` per shape could only ever say one colour.
 */
export interface OrnamentLayer {
  d: string
  /** `accent` is the page's second colour (the main one, half strength, when it gave none); `light` is white. */
  paint?: 'color' | 'accent' | 'light'
  /**
   * A stroke this many box units wide instead of a fill — on a fluid or a
   * motion, where the ribbon is part of the drawing and grows with it. On a
   * `line` every layer is already a stroke of the page's `weight`.
   */
  stroke?: number
  /** Filled even on a `line`: the dot at the end of a thread. */
  solid?: boolean
  opacity?: number
  /** On a `motion`, the layers that move; the rest hold still. */
  moves?: boolean
}

export interface Ornament {
  id: string
  kind: OrnamentKind
  /** Width over height it was drawn for. Patterns have none: they take their box. */
  ratio: number
  /** Paths in a 0–100 box (fill: `evenodd`; line: stroked, round caps). Empty for a pattern. */
  d: string
  /**
   * A fill made of OVERLAPPING pieces — the three bars of a bold asterisk, a
   * sun's rays over its disc — is filled `nonzero`: even-odd would punch a
   * hole wherever two of them cross.
   */
  nonzero?: boolean
  /** Drawn over `d`, in order. */
  layers?: readonly OrnamentLayer[]
  /** How a `motion` moves its moving layers: turning about its centre, or breathing. */
  motion?: 'spin' | 'pulse'
}

const r2 = (n: number) => Math.round(n * 100) / 100
const fmt = (n: number) => String(r2(n) === 0 ? 0 : r2(n))

/** A wave along `y` from x=`from` to x=`to`, as quadratics — `frameShapes.ts`'s waveEdge, open. */
function waveLine(from: number, to: number, y: number, amp: number, halves: number): string {
  const step = (to - from) / halves
  let d = `M${fmt(from)} ${fmt(y)}`
  for (let i = 0; i < halves; i++) {
    const x = from + step * i
    const sign = i % 2 === 0 ? -1 : 1
    d += `Q${fmt(x + step / 2)} ${fmt(y + sign * amp * 2)} ${fmt(x + step)} ${fmt(y)}`
  }
  return d
}

function zigzagLine(from: number, to: number, lo: number, hi: number, teeth: number): string {
  const step = (to - from) / (teeth * 2)
  let d = `M${fmt(from)} ${fmt(hi)}`
  for (let i = 1; i <= teeth * 2; i++) d += `L${fmt(from + step * i)} ${fmt(i % 2 ? lo : hi)}`
  return d
}

/**
 * A spiral of half circles around two centres four units apart, the classic
 * compass construction: each half turn is a plain arc, so no point is stored
 * that a renderer could round differently.
 */
function spiral(turns: number): string {
  let d = 'M50 50'
  for (let i = 1; i <= turns * 2; i++) {
    const r = i * 4
    // Odd half turns are centred on 54 and end on its right, even ones on 50
    // and end on its left: each starts where the last one ended.
    d += `A${r} ${r} 0 0 1 ${fmt(i % 2 ? 54 + r : 50 - r)} 50`
  }
  return d
}

/** Short strokes on a ring, like the rays of a sun drawn with a pen. */
function rays(n: number, inner: number, outer: number): string {
  let d = ''
  for (let i = 0; i < n; i++) {
    const a = -Math.PI / 2 + (i * 2 * Math.PI) / n
    d += `M${fmt(50 + Math.cos(a) * inner)} ${fmt(50 + Math.sin(a) * inner)}L${fmt(50 + Math.cos(a) * outer)} ${fmt(50 + Math.sin(a) * outer)}`
  }
  return d
}

const circlePath = (cx: number, cy: number, r: number) =>
  `M${fmt(cx)} ${fmt(cy - r)}A${fmt(r)} ${fmt(r)} 0 1 1 ${fmt(cx)} ${fmt(cy + r)}A${fmt(r)} ${fmt(r)} 0 1 1 ${fmt(cx)} ${fmt(cy - r)}Z`

type Pt = [number, number]
const pt = ([x, y]: Pt) => `${fmt(x)} ${fmt(y)}`
const polar = (r: number, deg: number, cx = 50, cy = 50): Pt => [cx + r * Math.cos((deg * Math.PI) / 180), cy + r * Math.sin((deg * Math.PI) / 180)]
const poly = (points: Pt[]) => `M${points.map(pt).join('L')}Z`

/** A star (or a regular polygon when `inner` is 1), first point straight up, radius 50. */
function star(points: number, inner: number): Pt[] {
  return Array.from({ length: points * 2 }, (_, i) => polar(i % 2 ? 50 * inner : 50, -90 + (i * 180) / points))
}

/**
 * A band of a ring between two angles (degrees, clockwise from 3 o'clock in a
 * y-down box): the arch of a rainbow, the quarter of a target.
 */
function ringBand(R: number, r: number, from: number, to: number, cx = 50, cy = 50, sy = 1): string {
  const large = to - from > 180 ? 1 : 0
  // `sy` stretches it down: on a 2:1 box a circle is twice as tall in box units.
  const at = (rad: number, deg: number): Pt => {
    const [x, y] = polar(rad, deg, cx, cy)
    return [x, cy + (y - cy) * sy]
  }
  return (
    `M${pt(at(R, from))}A${fmt(R)} ${fmt(R * sy)} 0 ${large} 1 ${pt(at(R, to))}` +
    `L${pt(at(r, to))}A${fmt(r)} ${fmt(r * sy)} 0 ${large} 0 ${pt(at(r, from))}Z`
  )
}

/**
 * A closed curve around the centre whose radius undulates `bumps` times, as
 * quadratics through the midpoints of its samples — smooth, and a tenth of the
 * length of the same curve as a polygon.
 */
function wavyCircle(bumps: number, R: number, amp: number): string {
  const n = bumps * 4
  const ctl = Array.from({ length: n }, (_, i) => polar(R + amp * Math.cos((i / n) * bumps * 2 * Math.PI), (i * 360) / n - 90))
  const mid = (a: Pt, b: Pt): Pt => [(a[0] + b[0]) / 2, (a[1] + b[1]) / 2]
  let d = `M${pt(mid(ctl[n - 1], ctl[0]))}`
  for (let i = 0; i < n; i++) d += `Q${pt(ctl[i])} ${pt(mid(ctl[i], ctl[(i + 1) % n]))}`
  return d + 'Z'
}

/** Petals on a circle, sized so their tips touch the box: R·cos(π/n) + R·sin(π/n) = 50. */
function petals(n: number): string {
  const R = 50 / (Math.cos(Math.PI / n) + Math.sin(Math.PI / n))
  const rr = R * Math.sin(Math.PI / n)
  const tips = Array.from({ length: n }, (_, i) => polar(R, -90 + (i * 360) / n))
  return `M${pt(tips[0])}` + tips.map((_, i) => `A${fmt(rr)} ${fmt(rr)} 0 0 1 ${pt(tips[(i + 1) % n])}`).join('') + 'Z'
}

/** A bar of `w` units across, through the centre, turned by `deg`. */
function bar(w: number, deg: number): string {
  const a = polar(50, deg)
  const b = polar(50, deg + 180)
  const [nx, ny] = [(-Math.sin((deg * Math.PI) / 180) * w) / 2, (Math.cos((deg * Math.PI) / 180) * w) / 2]
  return poly([
    [a[0] + nx, a[1] + ny],
    [b[0] + nx, b[1] + ny],
    [b[0] - nx, b[1] - ny],
    [a[0] - nx, a[1] - ny],
  ])
}

/**
 * A ribbon: a wave along `top`, then the same wave back along `top + thick`,
 * so the two edges stay parallel. `edge` draws one way of undulating.
 */
function ribbon(top: number, thick: number, edge: (from: number, to: number, y: number, sign: 1 | -1) => string): string {
  return `M0 ${fmt(top)}${edge(0, 100, top, 1)}L100 ${fmt(top + thick)}${edge(100, 0, top + thick, -1)}Z`
}
const waveEdge = (halves: number, amp: number) => (from: number, to: number, y: number, dir: 1 | -1) => {
  const step = (to - from) / halves
  let d = ''
  for (let i = 0; i < halves; i++) {
    // Walked backwards, the half-waves come in the reverse order: index them from the left.
    const k = dir === 1 ? i : halves - 1 - i
    d += `Q${pt([from + step * (i + 0.5), y + (k % 2 ? 1 : -1) * amp * 2])} ${pt([from + step * (i + 1), y])}`
  }
  return d
}
const zigEdge = (teeth: number, amp: number) => (from: number, to: number, y: number, dir: 1 | -1) => {
  const step = (to - from) / (teeth * 2)
  let d = ''
  for (let i = 1; i <= teeth * 2; i++) {
    const k = dir === 1 ? i : teeth * 2 - i
    d += `L${pt([from + step * i, y + (k % 2 ? -amp : 0)])}`
  }
  return d
}

/** Short arcs round a circle: a dotted ring drawn with a pen, no dash array to scale. */
function dottedCircle(r: number, dashes: number): string {
  const step = 360 / dashes
  return Array.from({ length: dashes }, (_, i) => `M${pt(polar(r, i * step))}A${fmt(r)} ${fmt(r)} 0 0 1 ${pt(polar(r, i * step + step * 0.5))}`).join('')
}

